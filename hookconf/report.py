"""Markdown matrix from one or more result files."""
from __future__ import annotations

import json
from typing import Any, Dict, List

from .levels import CORE_LEVELS, HARDENING, MAY_BE_UNTESTED, SURVEY_GROUPS, compute_levels

CELL = {"pass": "PASS", "fail": "FAIL", "unsupported": "UNSUPPORTED", "not_applicable": "n/a", "not_tested": "not tested", "error": "ERROR"}

TITLES = {
    "O1": "Pre + Post per tool type, same tool_use_id", "O2": "session_id, turn id, cwd, event name",
    "O3": "UserPromptSubmit prompt byte-for-byte", "O4": "subagent tool calls reach the hook",
    "B1": "deny stops shell + file-write canary", "B2": "B1 in bypass/YOLO mode", "B3": "deny reason reaches the model",
    "B4": "exit 2 + stderr = deny", "B5": "fail-closed on crash/hang/garbage", "B6": "hook failure is never silent",
    "A1": "ask prompts under auto-approve", "A2": "headless ask = deny + reason", "A2b": "headless ask honored under bypass mode", "A3": "file-edit content in payload",
    "A4": "prompt / transcript with tool outputs", "A5": "hook config protected from the agent",
    "A6": "config change mid-session keeps hooks", "P1": "PermissionRequest allow honored headless",
    "P2": "allow never beats managed deny", "P3": "remembered grant scope", "P4": "approve/reject decision event",
    "P5": "managed hook survives disable-all", "M1": "output replacement reaches the model", "M2": "provenance tags",
    "M3": "subagent agent_id + parent id + deny", "M4": "schema version in payload", "M5": "persistent transport",
}


def load(paths: List[str]) -> List[Dict[str, Any]]:
    docs = []
    for p in paths:
        with open(p, encoding="utf-8") as fh:
            docs.append(json.load(fh))
    return newest_per_run_key(docs)


def newest_per_run_key(docs: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """One result per (harness, version, OS): the one with the newest `date`.
    CI re-runs of a single job add a second result file for the same harness and
    OS (artifact names carry the attempt number); the matrix shows the latest.
    Order of first appearance is kept."""
    best: Dict[Any, Dict[str, Any]] = {}
    order: List[Any] = []
    for d in docs:
        key = (d.get("harness", {}).get("name"), d.get("harness", {}).get("version"), d.get("platform", {}).get("os"))
        if key not in best:
            order.append(key)
            best[key] = d
        elif str(d.get("date", "")) > str(best[key].get("date", "")):
            best[key] = d
    return [best[k] for k in order]


def _esc(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _kit(d: Dict[str, Any]) -> str:
    """Base kit SHA, plus the SHA of every merged partial run (e.g. `3517a57; A2b: 1a2b3c4`)."""
    bits = [d["kit"]["git_sha"]] + [f"{','.join(u.get('only') or ['all'])}: {u['kit']['git_sha']}"
                                    for u in d.get("updates", [])]
    return "; ".join(bits)


def _columns(docs: List[Dict[str, Any]]) -> List[str]:
    """`name version`; when two docs share it (same harness on two OSes in CI), add the OS."""
    cols = [f"{d['harness']['name']} {d['harness']['version']}" for d in docs]
    return [f"{c} ({d['platform']['os']})" if cols.count(c) > 1 else c for c, d in zip(cols, docs)]


def markdown(docs: List[Dict[str, Any]]) -> str:
    cols = _columns(docs)
    by = [{r["id"]: r for r in d["results"]} for d in docs]
    # always recomputed from the results, so old result files render with the current rules
    lv_docs = [compute_levels(d["results"]) for d in docs]
    out = ["# Hook conformance matrix", ""]
    out.append("Generated by hookconf from the result files. The evidence for each cell (probe records and mock "
               "model request excerpts) is in the JSON result under `results[].evidence`.")
    out.append("")
    out.append("**Core level** uses only the core requirements: L0 O1-O4, L1 B1-B4, L2 A1-A4 + A2b, L3 P1-P3, "
               "L4 M1+M3. A level is met when every tested core requirement in it passes; only "
               f"{', '.join(MAY_BE_UNTESTED)} may be untested, and a requirement that depends on an optional feature the "
               "harness does not have (subagents, bypass mode) is `n/a`; in both cases the level is marked `*` (not fully tested). `UNSUPPORTED` (the "
               "feature exists but the hook does not see it) blocks the level. "
               "**Hardening gaps** are the hardening requirements (" + ", ".join(HARDENING) + ") that failed or are "
               "unsupported; they do not change the core level. See README, \"Levels\".")
    out.append("")
    out.append("## Summary")
    out.append("")
    out.append("| Harness | Core level | Hardening gaps | Hardening not tested |")
    out.append("|---|---|---|---|")
    for col, lv in zip(cols, lv_docs):
        out.append(f"| {col} | **{lv['core']}** | {', '.join(lv['gap_labels']) or 'none found'} | "
                   f"{', '.join(lv['hardening_not_tested']) or '-'} |")
    out.append("")
    out.append("| Run | Harness version | OS | Kit SHA | Date |")
    out.append("|---|---|---|---|---|")
    for d in docs:
        dates = "; ".join([d["date"]] + [u["date"] for u in d.get("updates", [])])
        out.append(f"| {d['harness']['name']} | {d['harness']['version']} | {d['platform']['os']} | {_kit(d)} | {dates} |")
    out.append("")
    out.append("## Core levels")
    out.append("")
    out.append("| Level | " + " | ".join(cols) + " |")
    out.append("|---|" + "---|" * len(cols))
    for i, (lid, name, ids) in enumerate(CORE_LEVELS):
        cells = []
        for lv in lv_docs:
            pl = lv["per_level"][i]
            bits = ["met*" if pl["star"] else ("met" if pl["met"] else "not met")]
            if pl["blocking_status"]:
                bits.append("blocked by " + ", ".join(f"{k} ({v})" for k, v in pl["blocking_status"].items()))
            if not pl["passed"] and not pl["blocking_status"]:
                bits.append("nothing tested")
            if pl.get("not_applicable"):
                bits.append("n/a: " + ", ".join(pl["not_applicable"]))
            allowed = [i for i in pl["untested"] if i not in pl["blocking_status"]]
            if allowed:
                bits.append("untested: " + ", ".join(allowed))
            cells.append("; ".join(bits))
        out.append(f"| {lid} {name} ({', '.join(ids)}) | " + " | ".join(cells) + " |")
    out.append("")
    out.append("## Hardening")
    out.append("")
    out.append("| Id | Requirement | " + " | ".join(cols) + " |")
    out.append("|---|---|" + "---|" * len(cols))
    for rid in HARDENING:
        out.append(f"| {rid} | {TITLES.get(rid, '')} | " + " | ".join(CELL.get(lv['hardening'][rid], lv['hardening'][rid])
                                                              for lv in lv_docs) + " |")
    out.append("")
    out.append("## All requirements")
    out.append("")
    out.append("| Id | Requirement | Kind | " + " | ".join(cols) + " |")
    out.append("|---|---|---|" + "---|" * len(cols))
    for _, _, ids in SURVEY_GROUPS:
        for rid in ids:
            cells = []
            for b in by:
                r = b.get(rid)
                cells.append(CELL.get(r["status"], r["status"]) if r else "-")
            kind = "hardening" if rid in HARDENING else "core"
            out.append(f"| {rid} | {TITLES.get(rid, '')} | {kind} | " + " | ".join(cells) + " |")
    out.append("")
    for d, b, col in zip(docs, by, cols):
        out.append(f"## Details: {col}")
        out.append("")
        for _, _, ids in SURVEY_GROUPS:
            for rid in ids:
                r = b.get(rid)
                if r:
                    out.append(f"- **{rid} {CELL.get(r['status'], r['status'])}**: {_esc(r['summary'])}")
        out.append("")
        sessions = list(d.get("sessions", {}).values()) + [s for u in d.get("updates", []) for s in u.get("sessions", {}).values()]
        eg = sorted({e for s in sessions for e in s.get("egress_refused", [])})
        out.append(f"Outbound requests refused by the proxy sink during this run: {', '.join(eg) if eg else 'none'}.")
        out.append("")
    return "\n".join(out) + "\n"
